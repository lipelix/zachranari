/**
 * The service worker is generated at build time: `precacheList` picks what the build
 * emitted, `serviceWorkerSource` writes the worker with that list and the cache name
 * inlined. Pure functions, tested in node; the Vite plugin in `vite.config.ts` calls them.
 *
 * Every path is relative to the worker, so the same build runs at the root of a host
 * (Docker) and in a sub-folder (GitHub Pages: /zachranari/).
 */

/** Files worth caching, relative to the site root: the page, hashed assets, manifest, icons. */
export function precacheList(
  emitted: readonly string[],
  publicFiles: readonly string[],
): string[] {
  // Vite writes the page after plugins see the bundle: it is always part of the list.
  const paths = ["index.html", ...emitted, ...publicFiles]
    .filter((f) => !f.endsWith(".map") && f !== "sw.js")
    .map((f) => `./${f.replace(/^\.?\//, "")}`);
  return [...new Set(["./", ...paths])].sort((a, b) => {
    if (a === "./") return -1;
    if (b === "./") return 1;
    return a.localeCompare(b);
  });
}

/** `zachranari-<version>-<commit>`: every release caches under its own name. */
export const cacheName = (version: string, commit: string): string =>
  `zachranari-${version}-${commit}`;

/**
 * Install precaches everything and takes over at once (a kids' game has no "update?"
 * dialog: the next start simply runs the new version); activate drops older caches.
 * Hashed `assets/*` are cache-first, navigations network-first with the cached page
 * offline, everything else network with a cache fallback. Other origins are untouched.
 */
export function serviceWorkerSource(
  name: string,
  precache: readonly string[],
): string {
  return `// Generated by the serviceWorkerPlugin in vite.config.ts. Do not edit.
const CACHE = ${JSON.stringify(name)};
const PRECACHE = ${JSON.stringify(precache)};
// The folder the game lives in: "/" in Docker, "/zachranari/" on GitHub Pages.
const ROOT = new URL("./", self.location).pathname;
const PAGE = new URL("./index.html", self.location).href;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith("zachranari-") && key !== CACHE)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(ROOT)) return;

  if (url.pathname.startsWith(ROOT + "assets/")) {
    event.respondWith(
      caches.match(request, { ignoreVary: true }).then(
        (hit) =>
          hit ||
          fetch(request).then((response) => {
            const copy = response.clone();
            if (response.ok) caches.open(CACHE).then((cache) => cache.put(request, copy));
            return response;
          }),
      ),
    );
    return;
  }

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request).catch(() =>
        caches
          .match(PAGE, { ignoreSearch: true, ignoreVary: true })
          .then((hit) => hit || caches.match(ROOT)),
      ),
    );
    return;
  }

  event.respondWith(
    fetch(request).catch(() => caches.match(request, { ignoreSearch: true, ignoreVary: true })),
  );
});
`;
}
